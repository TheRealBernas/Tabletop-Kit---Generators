function getLanguage(language) {
	return language === 'pt' ? 'pt' : 'en';
}

function getText(language, key) {
	const selectedLanguage = getLanguage(language);
	return TEXT[selectedLanguage][key] ?? TEXT.en[key] ?? key;
}

function getLanguageName(language, uiLanguage) {
	return language === 'pt'
		? getText(uiLanguage, 'portuguese')
		: getText(uiLanguage, 'english');
}

module.exports = { getLanguage, getLanguageName, getText };
